//! WH3 start-game option pack generation.
//!
//! This module owns the pure byte-level generation for the lightweight launch
//! option pack used by the legacy TypeScript app as `!!!!out.pack`. Filesystem
//! writes and launch-list placement stay in runtime/launcher adapters.

