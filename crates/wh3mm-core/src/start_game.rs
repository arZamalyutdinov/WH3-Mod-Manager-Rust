/// Generated start-game pack file name used by the TS implementation.
pub const WH3_START_GAME_PACK_NAME: &str = "!!!!out.pack";
/// DB folder name used by WH3 battle permission tables.
pub const WH3_BATTLE_PERMISSIONS_DB_NAME: &str = "units_custom_battle_permissions_tables";
/// Packed DB table path generated by the TS `MakeUnitsGenerals` option.
pub const WH3_MAKE_UNITS_GENERALS_TABLE_PATH: &str =
    "db\\units_custom_battle_permissions_tables\\!!!!whmm_out";
/// Stable GUID used by the TS-generated battle-permission table.
pub const WH3_MAKE_UNITS_GENERALS_TABLE_GUID: &str = "129d32d8-3563-4d4f-8e19-a815e834e456";
/// DB version written by the TS-generated battle-permission table.
pub const WH3_MAKE_UNITS_GENERALS_TABLE_VERSION: i32 = 11;
/// WH3 vanilla data packs the TS implementation includes as start-game source
/// data when building generated `!!!!out.pack` options.
pub const WH3_START_GAME_SOURCE_PACK_NAMES: [&str; 3] =
    ["data.pack", "db.pack", "data_script.pack"];

/// Options supported by the Rust start-game pack generator.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
#[allow(clippy::struct_excessive_bools)]
pub struct Wh3StartGamePackOptions {
    /// Make units available as custom-battle generals.
    ///
    /// This TS option rewrites `units_custom_battle_permissions_tables` rows.
    /// Use `build_wh3_start_game_pack_with_battle_permissions(...)` when
    /// source rows are available.
    pub make_units_generals: bool,
    /// Replace WH3 intro movie files with a minimal blank movie payload.
    pub skip_intro_movies: bool,
    /// Enable game script console logging.
    pub script_logging: bool,
    /// Auto-click through frontend custom battle startup for testing.
    pub auto_start_custom_battle: bool,
}

/// Generated pack bytes and indexed file names.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedStartGamePack {
    /// Pack file name.
    pub pack_name: String,
    /// Complete `.pack` bytes.
    pub bytes: Vec<u8>,
    /// Packed file names written into the pack index.
    pub packed_file_names: Vec<String>,
}

/// Decoded enabled battle-permission tables plus the schema selected for them.
#[derive(Clone, Debug, PartialEq)]
pub struct Wh3BattlePermissionTables {
    /// Shared schema selected for decoded rows, if any table was found.
    pub schema: Option<DbVersionSchema>,
    /// Decoded DB rows in pack/index order.
    pub tables: Vec<DbRows>,
}

/// Builds WH3's `!!!!out.pack` for supported start-game options.
///
/// Returns `Ok(None)` when no supported options are enabled.
///
/// # Errors
///
/// Returns [`CoreError`] when generated sizes cannot fit the WH3 pack index
/// integer fields.
pub fn build_wh3_start_game_pack(
    options: &Wh3StartGamePackOptions,
) -> CoreResult<Option<GeneratedStartGamePack>> {
    if options.make_units_generals {
        return Err(CoreError::invalid_input(
            "MakeUnitsGenerals requires DB table rewriting and enabled battle-permission DB rows; use build_wh3_start_game_pack_with_battle_permissions",
        ));
    }

    let files = wh3_start_game_pack_files(options);
    if files.is_empty() {
        return Ok(None);
    }

    let packed_file_names = files.iter().map(|file| file.name.clone()).collect();
    Ok(Some(GeneratedStartGamePack {
        pack_name: WH3_START_GAME_PACK_NAME.to_string(),
        bytes: build_pfh5_pack_bytes(&files)?,
        packed_file_names,
    }))
}

/// Reads enabled WH3 battle-permission DB tables from pack paths.
///
/// # Errors
///
/// Returns [`CoreError`] when a pack cannot be read, a matching DB table cannot
/// be decoded, the schema cannot be resolved, or matching tables use
/// incompatible schemas.
pub fn read_wh3_battle_permission_tables_from_packs<P>(
    pack_paths: &[P],
    schema: &DbSchema,
) -> CoreResult<Wh3BattlePermissionTables>
where
    P: AsRef<Path>,
{
    let mut selected_schema = None::<DbVersionSchema>;
    let mut tables = Vec::new();

    for pack_path in pack_paths {
        let pack_path = pack_path.as_ref();
        let index = read_pack_index(pack_path, &PackReadOptions::default())?;
        for entry in &index.files {
            let PackFileKind::DbTable { db_name, .. } = entry.kind() else {
                continue;
            };
            if db_name != WH3_BATTLE_PERMISSIONS_DB_NAME {
                continue;
            }

            let metadata = read_packed_file_metadata(pack_path, entry)?;
            let PackFileMetadata::DbTable(metadata) = metadata else {
                continue;
            };
            let table_schema = resolve_table_schema(schema, &metadata).ok_or_else(|| {
                CoreError::parse(format!(
                    "could not resolve schema for {} version {:?}",
                    metadata.name, metadata.version
                ))
            })?;

            if let Some(existing_schema) = &selected_schema {
                if existing_schema.fields != table_schema.fields {
                    return Err(CoreError::parse(format!(
                        "incompatible battle-permission schema versions: {} and {}",
                        existing_schema.version, table_schema.version
                    )));
                }
            } else {
                selected_schema = Some(table_schema.clone());
            }

            tables.push(read_db_rows_from_pack(
                pack_path,
                entry,
                &table_schema.fields,
            )?);
        }
    }

    Ok(Wh3BattlePermissionTables {
        schema: selected_schema,
        tables,
    })
}

/// Builds WH3's `!!!!out.pack`, including `MakeUnitsGenerals` DB table output
/// when battle-permission source rows are supplied.
///
/// # Errors
///
/// Returns [`CoreError`] when generated pack sizes cannot fit WH3 pack fields,
/// `MakeUnitsGenerals` is enabled without source rows, or supplied DB rows
/// cannot be transformed/serialized with the supplied schema.
pub fn build_wh3_start_game_pack_with_battle_permissions(
    options: &Wh3StartGamePackOptions,
    battle_permission_tables: &[DbRows],
    battle_permission_schema: &[DbFieldSchema],
) -> CoreResult<Option<GeneratedStartGamePack>> {
    let mut files = Vec::new();

    if options.make_units_generals {
        files.push(PackFileWrite {
            name: WH3_MAKE_UNITS_GENERALS_TABLE_PATH.to_string(),
            payload: build_wh3_make_units_generals_payload(
                battle_permission_tables,
                battle_permission_schema,
            )?,
        });
    }
    files.extend(wh3_start_game_pack_files(options));

    if files.is_empty() {
        return Ok(None);
    }

    let packed_file_names = files.iter().map(|file| file.name.clone()).collect();
    Ok(Some(GeneratedStartGamePack {
        pack_name: WH3_START_GAME_PACK_NAME.to_string(),
        bytes: build_pfh5_pack_bytes(&files)?,
        packed_file_names,
    }))
}

/// Builds the generated `MakeUnitsGenerals` DB table payload from enabled
/// `units_custom_battle_permissions_tables` rows.
///
/// # Errors
///
/// Returns [`CoreError`] when no source rows are supplied, the schema does not
/// contain a Boolean `general_unit` field, or row serialization fails.
pub fn build_wh3_make_units_generals_payload(
    battle_permission_tables: &[DbRows],
    battle_permission_schema: &[DbFieldSchema],
) -> CoreResult<Vec<u8>> {
    let rows =
        build_wh3_make_units_generals_rows(battle_permission_tables, battle_permission_schema)?;
    write_db_rows_to_payload(&rows, battle_permission_schema)
}

/// Builds the generated `MakeUnitsGenerals` DB rows from enabled
/// `units_custom_battle_permissions_tables` rows.
///
/// # Errors
///
/// Returns [`CoreError`] when no source rows are supplied or the schema/rows do
/// not contain a Boolean `general_unit` field.
pub fn build_wh3_make_units_generals_rows(
    battle_permission_tables: &[DbRows],
    battle_permission_schema: &[DbFieldSchema],
) -> CoreResult<DbRows> {
    if battle_permission_tables.is_empty() {
        return Err(CoreError::invalid_input(
            "MakeUnitsGenerals requires at least one battle-permission DB table",
        ));
    }

    let general_unit_index = battle_permission_schema
        .iter()
        .position(|field| field.name == "general_unit")
        .ok_or_else(|| {
            CoreError::invalid_input("MakeUnitsGenerals schema is missing the general_unit field")
        })?;
    let general_unit_field = &battle_permission_schema[general_unit_index];
    if general_unit_field.field_type != DbFieldType::Boolean {
        return Err(CoreError::invalid_input(
            "MakeUnitsGenerals general_unit field must be Boolean",
        ));
    }

    let mut generated_rows = Vec::new();
    for (table_index, table) in battle_permission_tables.iter().enumerate() {
        let mut table_rows = Vec::with_capacity(table.rows.len());
        let mut duplicated_general_rows = Vec::new();
        for (row_index, row) in table.rows.iter().enumerate() {
            if row.len() != battle_permission_schema.len() {
                return Err(CoreError::invalid_input(format!(
                    "battle-permission table {table_index} row {row_index} has {} cells but schema has {} fields",
                    row.len(),
                    battle_permission_schema.len()
                )));
            }

            let mut transformed = row.clone();
            ensure_row_cell_names(
                table_index,
                row_index,
                &transformed,
                battle_permission_schema,
            )?;
            let general_unit = match &transformed[general_unit_index].value {
                DbPrimitiveValue::Boolean(value) => *value,
                _ => {
                    return Err(CoreError::invalid_input(format!(
                        "battle-permission table {table_index} row {row_index} general_unit value is not Boolean"
                    )));
                }
            };

            if general_unit == 1 {
                let mut duplicate = transformed.clone();
                duplicate[general_unit_index].value = DbPrimitiveValue::Boolean(0);
                duplicated_general_rows.push(duplicate);
            } else {
                transformed[general_unit_index].value = DbPrimitiveValue::Boolean(1);
            }
            table_rows.push(transformed);
        }

        table_rows.extend(duplicated_general_rows);
        generated_rows.extend(table_rows);
    }

    Ok(DbRows {
        guid: Some(WH3_MAKE_UNITS_GENERALS_TABLE_GUID.to_string()),
        version: Some(WH3_MAKE_UNITS_GENERALS_TABLE_VERSION),
        rows: generated_rows,
    })
}

fn wh3_start_game_pack_files(options: &Wh3StartGamePackOptions) -> Vec<PackFileWrite> {
    let mut files = Vec::new();

    if options.skip_intro_movies {
        files.extend(WH3_INTRO_MOVIES.iter().map(|name| PackFileWrite {
            name: (*name).to_string(),
            payload: EMPTY_MOVIE.to_vec(),
        }));
    }
    if options.script_logging {
        files.push(PackFileWrite {
            name: "script\\enable_console_logging".to_string(),
            payload: vec![0x00],
        });
    }
    if options.auto_start_custom_battle {
        files.push(PackFileWrite {
            name: "script\\frontend\\mod\\pj_auto_custom_battles.lua".to_string(),
            payload: AUTO_START_CUSTOM_BATTLE_SCRIPT.as_bytes().to_vec(),
        });
    }

    files
}
fn ensure_row_cell_names(
    table_index: usize,
    row_index: usize,
    row: &[DbCell],
    schema: &[DbFieldSchema],
) -> CoreResult<()> {
    for (field, cell) in schema.iter().zip(row) {
        if cell.name != field.name {
            return Err(CoreError::invalid_input(format!(
                "battle-permission table {table_index} row {row_index} expected field {} but found {}",
                field.name, cell.name
            )));
        }
    }

    Ok(())
}

